# ---------------------------------------------------------------- Βοηθητικές συναρτήσεις
def to_excel_bytes(sheets):
    """Μετατρέπει {όνομα φύλλου: DataFrame} σε αρχείο Excel (bytes)."""
    out = io.BytesIO()
    with pd.ExcelWriter(out, engine="openpyxl") as writer:
        for name, df in sheets.items():
            df.to_excel(writer, index=False, sheet_name=name[:31])
    return out.getvalue()


def to_png_bytes(fig):
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=200, bbox_inches="tight", facecolor="white")
    return buf.getvalue()


def fmt_dates(df, cols):
    """Επιστρέφει αντίγραφο με ημερομηνίες σε μορφή ΗΗ/ΜΜ/ΕΕΕΕ για εμφάνιση."""
    out = df.copy()
    for c in cols:
        if c in out:
            out[c] = pd.to_datetime(out[c]).dt.strftime("%d/%m/%Y")
    return out


def missing_columns(df, required):
    return [c for c in required if c not in df.columns]


def load_input(key, required, sample_fn, sample_label):
    """Κοινή φόρμα εισαγωγής: παράδειγμα ή αρχείο Excel. Επιστρέφει DataFrame ή None."""
    source = st.radio("Δεδομένα", [f"📎 {sample_label}", "📂 Δικό μου αρχείο Excel"],
                      horizontal=True, key=f"{key}_src")
    if source.startswith("📎"):
        df = sample_fn()
        st.download_button("⬇️ Κατέβασε το παράδειγμα σε Excel (ως πρότυπο)",
                           to_excel_bytes({"Δεδομένα": df}), f"{key}_παράδειγμα.xlsx", key=f"{key}_dl")
        return df
    uploaded = st.file_uploader("Ανέβασε αρχείο Excel (.xlsx)", type=["xlsx"], key=f"{key}_up")
    st.caption("Απαιτούμενες στήλες: " + " · ".join(required))
    if uploaded is None:
        st.info("Ανέβασε αρχείο ή χρησιμοποίησε το παράδειγμα για να ξεκινήσεις.")
        return None
    try:
        df = pd.read_excel(uploaded)
    except Exception as e:
        st.error(f"Δεν ήταν δυνατή η ανάγνωση του αρχείου: {e}")
        return None
    miss = missing_columns(df, required)
    if miss:
        st.error("Λείπουν οι στήλες: " + ", ".join(miss) +
                 ". Κατέβασε το παράδειγμα για να δεις τη σωστή μορφή.")
        return None
    return df


